import B from './Secret/BigInt'
import R from './Secret/RSA'

const RSA_MODULUS = 'DBCC53814668BD44D2185B1195A00C5222DAB190AEF5397E6466918D560337ECA438CF8725BA35A2F38B79BC7C1A441ED610D361B990008A47B42633C23D6674DC8545032BF161B83FE0E1B7609D1A8DD72B23AEDC60830A1614D9A7D22A3419FC9616BA858FC9D2D4A390B6A4D3CE5488CAD6F4264A1412E5E30FF372C80515'

export function encryptPassword(password) {
  B.setMaxDigits(129)
  const key = new R.RSAKeyPair('010001', '', RSA_MODULUS)
  return R.encryptedString(key, password)
}
